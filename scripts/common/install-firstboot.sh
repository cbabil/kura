#!/bin/bash
# scripts/common/install-firstboot.sh
# Build-time helpers that prepare an image to become a unique device on its
# first boot. Source this file; it defines functions only.

# install_firstboot <rootfs> <brand> <os-name> <firstboot-script>
# Installs the first-boot script and two units:
#   <brand>-ssh-keygen.service  generates SSH host keys before sshd starts.
#                               Standalone so SSH never waits for Docker.
#   <brand>-firstboot.service   grows the root partition, loads saved images
#                               and creates tomod's network, after Docker and
#                               before tomod and the supervisor.
install_firstboot() {
    local rootfs="$1" brand="$2" name="$3" src="$4"
    local units="${rootfs}/usr/lib/systemd/system"
    local wants="${rootfs}/etc/systemd/system/multi-user.target.wants"

    install -d "${rootfs}/usr/lib/${brand}" "${units}" "${wants}"
    sed "s|__BRAND_NAME__|${name}|g; s|__BRAND__|${brand}|g" "${src}" \
        > "${rootfs}/usr/lib/${brand}/firstboot.sh"
    chmod 0755 "${rootfs}/usr/lib/${brand}/firstboot.sh"

    cat > "${units}/${brand}-ssh-keygen.service" <<EOF
[Unit]
Description=${name} SSH host key generation
Before=ssh.service
ConditionPathExists=!/etc/ssh/ssh_host_ed25519_key

[Service]
Type=oneshot
ExecStart=/usr/bin/ssh-keygen -A
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF

    cat > "${units}/${brand}-firstboot.service" <<EOF
[Unit]
Description=${name} first boot setup
Wants=docker.service
After=docker.service
Before=tomod.service ${brand}-supervisor.service
ConditionPathExists=!/var/lib/${brand}/.firstboot-done

[Service]
Type=oneshot
ExecStart=/usr/lib/${brand}/firstboot.sh
RemainAfterExit=yes
TimeoutStartSec=600
StandardOutput=journal+console
StandardError=journal+console

[Install]
WantedBy=multi-user.target
EOF

    ln -sf "/usr/lib/systemd/system/${brand}-ssh-keygen.service" \
        "${wants}/${brand}-ssh-keygen.service"
    ln -sf "/usr/lib/systemd/system/${brand}-firstboot.service" \
        "${wants}/${brand}-firstboot.service"
}

# reset_device_identity <rootfs>
# Removes identity generated while building, so each flashed device gets its
# own: SSH host keys (regenerated by <brand>-ssh-keygen.service) and the
# machine ID (an empty /etc/machine-id makes systemd create one at boot).
reset_device_identity() {
    local rootfs="$1"
    rm -f "${rootfs}"/etc/ssh/ssh_host_*
    : > "${rootfs}/etc/machine-id"
    rm -f "${rootfs}/var/lib/dbus/machine-id"
}
